import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ARTIFACT_PATH = resolve(ROOT, "contracts/cli-http-v1.schema.json");
const LOCK_PATH = resolve(ROOT, "contracts/cli-http-v1.lock.json");
const TYPES_PATH = resolve(ROOT, "src/generated/cli-http-v1.types.ts");
const VALIDATORS_PATH = resolve(ROOT, "src/generated/cli-http-v1.validators.js");
const DECLARATIONS_PATH = resolve(ROOT, "src/generated/cli-http-v1.validators.d.ts");
const SOURCE_REPOSITORY = "campus-ai/primitive";
const SOURCE_PATH = "contracts/cli-http-v1.schema.json";
const DRAFT_2020_12 = "https://json-schema.org/draft/2020-12/schema";
const GENERATED_HEADER =
  "// Generated by scripts/generate-cli-contract.mjs from contracts/cli-http-v1.schema.json. Do not edit.\n";

export const SUPPORTED_RUNTIME_REFINEMENTS = new Set([
  "canonical_lowercase_workspace_uuid",
  "canonical_repository_paths",
  "complete_coverage_requires_path",
  "degrade_invalid_rollout_fields",
  "proposal_utf8_max_6144",
  "safe_feedback_event_id",
  "safe_feedback_session_id",
  "unique_feedback_event_ids",
  "unique_repository_paths",
]);

function parseObject(bytes, label) {
  let value;
  try {
    value = JSON.parse(bytes.toString("utf8"));
  } catch (error) {
    throw new Error(`${label} is not valid JSON`, { cause: error });
  }
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(`${label} must be a JSON object`);
  }
  return value;
}

function nonemptyString(value, label) {
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`${label} must be a non-empty string`);
  }
  return value;
}

function refinementLocation(path) {
  const definitionName = path[0] === "$defs" ? path[1] : undefined;
  return typeof definitionName === "string"
    ? `definition ${definitionName}`
    : `schema at /${path.join("/")}`;
}

function assertRuntimeRefinements(value, definitionNames, path = []) {
  if (Array.isArray(value)) {
    value.forEach((item, index) =>
      assertRuntimeRefinements(item, definitionNames, [...path, String(index)]),
    );
    return;
  }
  if (typeof value !== "object" || value === null) {
    return;
  }

  if (Object.hasOwn(value, "x-primitive-runtime-refinements")) {
    const refinements = value["x-primitive-runtime-refinements"];
    const location = refinementLocation(path);
    if (!Array.isArray(refinements) || refinements.some((item) => typeof item !== "string")) {
      throw new Error(`${location} has malformed runtime refinements`);
    }
    for (const refinement of refinements) {
      if (!SUPPORTED_RUNTIME_REFINEMENTS.has(refinement)) {
        throw new Error(`${location} uses unsupported runtime refinement: ${refinement}`);
      }
    }
    const atDefinitionRoot =
      path.length === 2 && path[0] === "$defs" && definitionNames.has(path[1]);
    if (!atDefinitionRoot) {
      throw new Error(`${location} uses runtime refinements outside a definition root`);
    }
  }

  for (const [key, child] of Object.entries(value)) {
    if (key !== "x-primitive-runtime-refinements") {
      assertRuntimeRefinements(child, definitionNames, [...path, key]);
    }
  }
}

function assertArtifactLock(artifactBytes, artifact, lock) {
  const digest = createHash("sha256").update(artifactBytes).digest("hex");
  if (lock.sha256 !== digest) {
    throw new Error(
      `contract artifact checksum mismatch: expected ${String(lock.sha256)}, got ${digest}`,
    );
  }
  if (artifact.$schema !== DRAFT_2020_12) {
    throw new Error(`unsupported JSON Schema dialect: ${String(artifact.$schema)}`);
  }
  if (artifact.$id !== lock.artifactId) {
    throw new Error("contract artifact ID does not match its lock");
  }
  if (artifact["x-primitive-contract-version"] !== lock.contractVersion) {
    throw new Error("contract version does not match its lock");
  }
  if (artifact["x-primitive-scope"] !== lock.scope) {
    throw new Error("contract scope does not match its lock");
  }
  if (lock.sourceRepository !== SOURCE_REPOSITORY) {
    throw new Error(`sourceRepository must be ${SOURCE_REPOSITORY}`);
  }
  if (!/^[0-9a-f]{40}$/u.test(nonemptyString(lock.sourceCommit, "sourceCommit"))) {
    throw new Error("sourceCommit must be a full lowercase Git object ID");
  }
  if (lock.sourcePath !== SOURCE_PATH) {
    throw new Error(`sourcePath must be ${SOURCE_PATH}`);
  }
}

function definitionEntries(artifact) {
  const definitions = artifact.$defs;
  if (typeof definitions !== "object" || definitions === null || Array.isArray(definitions)) {
    throw new Error("contract artifact must define $defs");
  }
  const entries = Object.entries(definitions).sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  );
  if (entries.length === 0) {
    throw new Error("contract artifact has no definitions");
  }
  for (const [name, schema] of entries) {
    if (!/^[A-Za-z][A-Za-z0-9]*$/u.test(name)) {
      throw new Error(`definition name is not a TypeScript identifier: ${name}`);
    }
    if (typeof schema !== "object" || schema === null || Array.isArray(schema)) {
      throw new Error(`definition ${name} must be a JSON Schema object`);
    }
  }
  return entries;
}

function assertOperationReferences(artifact, definitionNames) {
  const operations = artifact["x-primitive-operations"];
  if (typeof operations !== "object" || operations === null || Array.isArray(operations)) {
    throw new Error("contract artifact must define x-primitive-operations");
  }
  for (const [operationName, operation] of Object.entries(operations)) {
    if (typeof operation !== "object" || operation === null || Array.isArray(operation)) {
      throw new Error(`operation ${operationName} must be an object`);
    }
    for (const key of ["request", "success", "error"]) {
      if (!(key in operation)) {
        continue;
      }
      const reference = operation[key]?.$ref;
      const prefix = "#/$defs/";
      if (typeof reference !== "string" || !reference.startsWith(prefix)) {
        throw new Error(`operation ${operationName}.${key} must use a local definition reference`);
      }
      if (!definitionNames.has(reference.slice(prefix.length))) {
        throw new Error(`operation ${operationName}.${key} references an unknown definition`);
      }
    }
  }
}

async function generateTypes(entries) {
  const sections = [];
  for (const [name, schema] of entries) {
    sections.push(
      await compile(schema, name, {
        bannerComment: "",
        declareExternallyReferenced: true,
        enableConstEnums: false,
        format: true,
        strictIndexSignatures: true,
        unreachableDefinitions: false,
      }),
    );
  }
  return `${GENERATED_HEADER}${sections.join("\n")}`;
}

function validatorExportName(name, schema) {
  const refinements = schema["x-primitive-runtime-refinements"];
  return `is${name}${Array.isArray(refinements) && refinements.length > 0 ? "Structure" : ""}`;
}

function convertAjvRuntimeImports(source) {
  const converted = source.replace(
    /const ([A-Za-z0-9_$]+) = require\("(ajv\/dist\/runtime\/[^".]+)"\)\.default;/gu,
    (_match, localName, moduleName) => `import ${localName} from "${moduleName}.js";`,
  );
  if (converted.includes("require(")) {
    throw new Error("Ajv emitted an unsupported CommonJS runtime dependency");
  }
  return converted;
}

function generateValidators(artifact, entries) {
  const ajv = new Ajv2020({
    allErrors: false,
    code: { esm: true, lines: true, optimize: 1, source: true },
    coerceTypes: false,
    removeAdditional: false,
    strict: true,
    useDefaults: false,
    validateFormats: false,
  });
  for (const keyword of [
    "x-primitive-contract-version",
    "x-primitive-operations",
    "x-primitive-runtime-refinements",
    "x-primitive-scope",
  ]) {
    ajv.addKeyword({ keyword, valid: true });
  }
  ajv.addSchema(artifact, artifact.$id);
  const exports = {};
  for (const [name, schema] of entries) {
    const id = `urn:primitive:cli-http-v1:${name}`;
    ajv.addSchema({ $id: id, $ref: `${artifact.$id}#/$defs/${name}` }, id);
    exports[validatorExportName(name, schema)] = id;
  }
  const source = convertAjvRuntimeImports(standaloneCode(ajv, exports));
  return `${GENERATED_HEADER}${source.endsWith("\n") ? source : `${source}\n`}`;
}

function generateDeclarations(entries) {
  const imports = entries.map(([name]) => name).join(", ");
  const declarations = entries
    .map(
      ([name, schema]) =>
        `export declare const ${validatorExportName(name, schema)}: (value: unknown) => value is ${name};`,
    )
    .join("\n");
  return `${GENERATED_HEADER}import type { ${imports} } from "./cli-http-v1.types.js";\n\n${declarations}\n`;
}

export async function buildGeneratedOutputs(artifactBytes, lockBytes) {
  const artifact = parseObject(artifactBytes, "contract artifact");
  const lock = parseObject(lockBytes, "contract lock");
  assertArtifactLock(artifactBytes, artifact, lock);
  const entries = definitionEntries(artifact);
  const definitionNames = new Set(entries.map(([name]) => name));
  assertRuntimeRefinements(artifact, definitionNames);
  assertOperationReferences(artifact, definitionNames);
  return {
    [TYPES_PATH]: await generateTypes(entries),
    [VALIDATORS_PATH]: generateValidators(artifact, entries),
    [DECLARATIONS_PATH]: generateDeclarations(entries),
  };
}

function writeOutputs(outputs) {
  for (const [path, contents] of Object.entries(outputs)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents, "utf8");
  }
}

function checkOutputs(outputs) {
  const stale = [];
  for (const [path, expected] of Object.entries(outputs)) {
    let actual;
    try {
      actual = readFileSync(path, "utf8");
    } catch {
      actual = undefined;
    }
    if (actual !== expected) {
      stale.push(path.slice(ROOT.length + 1));
    }
  }
  if (stale.length > 0) {
    throw new Error(`generated contract bindings are stale: ${stale.join(", ")}`);
  }
}

async function main() {
  const mode = process.argv[2];
  if (!new Set(["--write", "--check"]).has(mode) || process.argv.length !== 3) {
    throw new Error("usage: node scripts/generate-cli-contract.mjs --write|--check");
  }
  const outputs = await buildGeneratedOutputs(readFileSync(ARTIFACT_PATH), readFileSync(LOCK_PATH));
  if (mode === "--write") {
    writeOutputs(outputs);
  } else {
    checkOutputs(outputs);
  }
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : undefined;
if (invokedPath === fileURLToPath(import.meta.url)) {
  await main();
}
